"""Write the frozen RL policy table as C (src/rl_table.h) and as config/rl_policy.json.

Input: a .npy table of shape [4][3][3] (state -> next q index), as produced by
train_rl.py. Run:  python3 tools/export_rl_table.py rl_table_frozen.npy
"""
import json, sys
import numpy as np

src = sys.argv[1]
table = np.load(src).astype(int)
assert table.shape == (4, 3, 3), table.shape
assert table.min() >= 0 and table.max() <= 3

groups = []
for i in range(4):
    inner = ', '.join('{' + ', '.join(str(int(table[i, b, l])) for l in range(3)) + '}' for b in range(3))
    groups.append('    {' + inner + '}')
body = ',\n'.join(groups)
header = f"""/* rl_table.h - GENERATED by tools/export_rl_table.py from {src}. Do not edit.
 * RL_TABLE[q_index][miss_bucket][load_bucket] = next q_index.
 * q_index: 0..3 for q = 1, 2, 4, 8.
 * miss_bucket: 0 if miss <= 1 %, 1 if <= 5 %, 2 if > 5 %.
 * load_bucket: 0 if fg reads in the window < 100, 1 if < 500, 2 otherwise.
 */
#ifndef RL_TABLE_H
#define RL_TABLE_H
#include <stdint.h>
static const uint8_t RL_TABLE[4][3][3] = {{
{body}
}};
#endif
"""
open('src/rl_table.h', 'w').write(header)

cfg = {
    "policy": "rl",
    "levels": [1, 2, 4, 8],
    "q_start": 1,
    "window_ms": 1000,
    "target_ms": 0.5,
    "min_samples": 25,
    "state": "(q_index, miss bucket of this window, load bucket of this window)",
    "miss_buckets": "<=0.01, <=0.05, >0.05",
    "load_buckets": "fg reads per window <100, <500, >=500",
    "table": table.tolist(),
    "_note": "Trained in a simulator fitted to Milestone 3 logs (penalty 6.0). Not validated on the real disk until the Milestone 4 held-out runs.",
}
json.dump(cfg, open('config/rl_policy.json', 'w'), indent=2)
print('wrote src/rl_table.h and config/rl_policy.json')
